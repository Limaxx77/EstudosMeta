type Opts = [string, string, string, string];

/**
 * Distribui a posição da resposta correta de forma determinística (pelo id),
 * para o gabarito não ficar concentrado em uma letra. Alternativas
 * puramente numéricas (anos, quantidades) ficam em ordem crescente.
 * Por isso, as explicações nunca citam letras.
 */
function place(id: string, options: Opts, answer: 0 | 1 | 2 | 3): [Opts, 0 | 1 | 2 | 3] {
  const correct = options[answer];
  if (options.every((o) => /^\d+$/.test(o.trim()))) {
    const sorted = [...options].sort((a, b) => Number(a) - Number(b)) as Opts;
    return [sorted, sorted.indexOf(correct) as 0 | 1 | 2 | 3];
  }
  let h = 0;
  for (const ch of id) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  const target = (h % 4) as 0 | 1 | 2 | 3;
  const opts = [...options] as Opts;
  [opts[answer], opts[target]] = [opts[target], opts[answer]];
  return [opts, target];
}

const q = (
  id: string,
  subject: SubjectId,
  topic: string,
  statement: string,
  options: Opts,
  answer: 0 | 1 | 2 | 3,
  explanation: string,
): Question => {
  const [opts, ans] = place(id, options, answer);
  return { id, subject, topic, statement, options: opts, answer: ans, explanation };
};

